# Case summary (records / insurance)
# ---------------------------------------------------------------------------
def generate_case_summary_pdf(patient: dict, case: dict, payments: list,
                                prescriptions: list, doctor_name: str, clinic: dict,
                                purpose: str = "record", logo_path: str = None,
                                amendments: list = None) -> bytes:
    buf = io.BytesIO()
    story = []
    story += _letterhead(clinic, logo_path)
    title = "CASE SUMMARY — INSURANCE CLAIM" if purpose == "insurance" else "CASE SUMMARY"
    story.append(Paragraph(title, styles["DocTitle"]))

    story.append(Paragraph("Patient Details", ParagraphStyle("Sub", parent=styles["Heading4"],
                                                               textColor=MUTED)))
    patient_rows = [
        ("Name", patient.get("name")),
        ("Age / Sex", f"{patient.get('age') or '—'} / {patient.get('sex') or '—'}"),
        ("Mobile", patient.get("mobile")),
        ("Address", patient.get("address")),
    ]
    medical_bits = list(patient.get("medical_conditions") or [])
    if patient.get("medical_conditions_other"):
        medical_bits.append(patient["medical_conditions_other"])
    if medical_bits:
        patient_rows.append(("Medical Conditions", ", ".join(medical_bits)))
    allergy_bits = list(patient.get("allergies") or [])
    if patient.get("allergies_other"):
        allergy_bits.append(patient["allergies_other"])
    if allergy_bits:
        patient_rows.append(("Allergies", ", ".join(allergy_bits)))
    if patient.get("is_pregnant") or patient.get("is_nursing"):
        status_bits = []
        if patient.get("is_pregnant"):
            status_bits.append("Pregnant")
        if patient.get("is_nursing"):
            status_bits.append("Nursing")
        patient_rows.append(("Status", ", ".join(status_bits)))
    story.append(_info_table(patient_rows))
    story.append(Spacer(1, 10))

    story.append(Paragraph("Case Details", ParagraphStyle("Sub2", parent=styles["Heading4"],
                                                            textColor=MUTED)))
    procedures = ", ".join(case.get("procedures") or []) or "—"
    if case.get("custom_procedure"):
        procedures += f" ({case['custom_procedure']})"
    story.append(_info_table([
        ("Case Title", case.get("title")),
        ("Status", case.get("status")),
        ("Procedures", procedures),
        ("Treating Doctor", doctor_name or "—"),
        ("Case Opened", case.get("created_at")),
        ("Case Closed", case.get("closed_at") or "—"),
    ]))
    story.append(Spacer(1, 10))

    total_cost = case.get("total_cost", 0)
    total_paid = sum(p["amount"] for p in payments)
    balance = round(total_cost - total_paid, 2)

    story.append(Paragraph("Cost Details", ParagraphStyle("Sub3", parent=styles["Heading4"],
                                                            textColor=MUTED)))
    cost_table = Table([
        ["Total Treatment Cost", _money(total_cost)],
        ["Total Paid", _money(total_paid)],
        ["Balance Due" if case.get("status") == "Active" else "Balance at Closure", _money(balance)],
    ], colWidths=[80 * mm, 50 * mm])
    cost_table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE", (0, 0), (-1, -1), 10.5),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("LINEBELOW", (0, 0), (-1, -2), 0.4, BORDER),
        ("LINEABOVE", (0, -1), (-1, -1), 0.8, PRIMARY),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
    ]))
    story.append(cost_table)
    story.append(Spacer(1, 10))

    if amendments:
        story.append(Paragraph("Cost Revision History", ParagraphStyle("Sub3b", parent=styles["Heading4"],
                                                                         textColor=MUTED)))
        data = [["Date", "Previous", "Revised To", "Reason"]]
        for a in sorted(amendments, key=lambda x: x["amended_at"]):
            data.append([a["amended_at"], _money(a["previous_cost"]), _money(a["new_cost"]),
                         a.get("reason") or ""])
        at = Table(data, colWidths=[24 * mm, 26 * mm, 26 * mm, None])
        at.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("ALIGN", (1, 1), (2, -1), "RIGHT"),
            ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ACCENT]),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(at)
        story.append(Spacer(1, 10))

    if payments:
        story.append(Paragraph("Payment History", ParagraphStyle("Sub4", parent=styles["Heading4"],
                                                                   textColor=MUTED)))
        data = [["Date", "Amount", "Method", "Note"]]
        for p in payments:
            data.append([p["payment_date"], _money(p["amount"]), p.get("method") or "—",
                         p.get("note") or ""])
        pt = Table(data, colWidths=[28 * mm, 30 * mm, 28 * mm, None])
        pt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 9.5),
            ("ALIGN", (1, 1), (1, -1), "RIGHT"),
            ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ACCENT]),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(pt)
        story.append(Spacer(1, 10))

    if prescriptions:
        story.append(Paragraph("Prescription History", ParagraphStyle("Sub5", parent=styles["Heading4"],
                                                                        textColor=MUTED)))
        for rx in prescriptions:
            rx_html = (rx['rx_details'] or "").replace("\n", "<br/>")
            story.append(Paragraph(f"<b>{rx['rx_date']}</b> — {rx_html}", styles["Body"]))
            story.append(Spacer(1, 4))

    if purpose == "insurance":
        story.append(Spacer(1, 10))
        story.append(Paragraph(
            "This document summarizes the treatment case and associated costs for "
            "insurance claim / reimbursement purposes.", styles["ClinicMeta"]))

    story += _footer()
    return _build(buf, story)


