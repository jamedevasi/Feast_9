def generate_report_pdf(start_date: str, end_date: str, stats: dict, payments: list,
                          closed_cases: list, clinic: dict, logo_path: str = None,
                          revenue_summary: dict = None) -> bytes:
    buf = io.BytesIO()
    story = []
    story += _letterhead(clinic, logo_path)
    story.append(Paragraph("PRACTICE REPORT", styles["DocTitle"]))
    story.append(Paragraph(f"Period: {start_date} to {end_date}", styles["ClinicMeta"]))
    story.append(Spacer(1, 10))

    if revenue_summary:
        story.append(Paragraph("Revenue Overview — All Time", ParagraphStyle(
            "RevSub", parent=styles["Heading4"], textColor=MUTED)))
        rev_data = [
            ["Total Billed", "Total Collected", "Total Pending", "Collection Rate"],
            [
                _money(revenue_summary["total_billed"]),
                _money(revenue_summary["total_collected"]),
                _money(revenue_summary["total_pending"]),
                f"{revenue_summary['collection_rate']}%",
            ],
        ]
        rt = Table(rev_data, colWidths=[None]*4)
        rt.setStyle(TableStyle([
            ("BACKGROUND", (0,0), (-1,0), PRIMARY),
            ("TEXTCOLOR", (0,0), (-1,0), colors.white),
            ("FONTSIZE", (0,0), (-1,-1), 9),
            ("ALIGN", (0,0), (-1,-1), "CENTER"),
            ("GRID", (0,0), (-1,-1), 0.4, BORDER),
            ("BACKGROUND", (0,1), (-1,1), ACCENT),
            ("FONTSIZE", (0,1), (-1,1), 10),
            ("FONTNAME", (0,1), (-1,1), "Helvetica-Bold"),
            ("TOPPADDING", (0,0), (-1,-1), 6),
            ("BOTTOMPADDING", (0,0), (-1,-1), 6),
        ]))
        story.append(rt)
        story.append(Spacer(1, 10))

    summary_data = [
        ["Revenue Collected", _money(stats.get("revenue", 0))],
        ["Cases Closed", str(stats.get("cases_closed", 0))],
        ["New Cases Opened", str(stats.get("new_cases", 0))],
        ["New Patients Registered", str(stats.get("new_patients", 0))],
    ]
    st = Table(summary_data, colWidths=[80 * mm, 50 * mm])
    st.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 11),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("BACKGROUND", (0, 0), (-1, -1), ACCENT),
        ("BOX", (0, 0), (-1, -1), 0.6, BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
    ]))
    story.append(st)
    story.append(Spacer(1, 14))

    if payments:
        story.append(Paragraph(f"Payments received ({len(payments)})",
                                ParagraphStyle("Sub", parent=styles["Heading4"], textColor=MUTED)))
        data = [["Date", "Patient", "Case", "Amount"]]
        for p in payments[:500]:
            data.append([p["payment_date"], p.get("patient_name", ""), p.get("case_title", ""),
                         _money(p["amount"])])
        pt = Table(data, colWidths=[24 * mm, 40 * mm, 50 * mm, None])
        pt.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("ALIGN", (3, 1), (3, -1), "RIGHT"),
            ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ACCENT]),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(pt)
        if len(payments) > 500:
            story.append(Paragraph(f"...and {len(payments) - 500} more (see CSV export for the full list).",
                                    styles["ClinicMeta"]))
        story.append(Spacer(1, 12))

    if closed_cases:
        story.append(Paragraph(f"Cases closed ({len(closed_cases)})",
                                ParagraphStyle("Sub2", parent=styles["Heading4"], textColor=MUTED)))
        data = [["Closed On", "Patient", "Case", "Total Cost"]]
        for c in closed_cases[:500]:
            data.append([c["closed_at"], c.get("patient_name", ""), c["title"], _money(c["total_cost"])])
        ct = Table(data, colWidths=[24 * mm, 40 * mm, 50 * mm, None])
        ct.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("ALIGN", (3, 1), (3, -1), "RIGHT"),
            ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ACCENT]),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(ct)

    story += _footer()
    return _build(buf, story)


