"""
PDF generation using reportlab — prescriptions, per-case and per-patient
summaries (for records/insurance), and date-range stat reports.

Every PDF starts with a shared letterhead (clinic name/logo/address) so the
Feast9 branding is consistent everywhere documents are printed.
"""
import io
import os
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_RIGHT
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image, HRFlowable,
)
from reportlab.pdfgen import canvas as pdfcanvas

PRIMARY = colors.HexColor("#2E7D32")
PRIMARY_LIGHT = colors.HexColor("#8BC34A")
ACCENT = colors.HexColor("#E8F5E9")
TEXT = colors.HexColor("#1B2B1E")
MUTED = colors.HexColor("#5B6B5E")
BORDER = colors.HexColor("#CFE3D0")
DANGER = colors.HexColor("#C62828")

styles = getSampleStyleSheet()
styles.add(ParagraphStyle("BrandTitle", parent=styles["Heading1"], textColor=PRIMARY,
                           fontSize=18, leading=22, spaceAfter=0))
styles.add(ParagraphStyle("ClinicMeta", parent=styles["Normal"], textColor=MUTED,
                           fontSize=9, leading=12))
styles.add(ParagraphStyle("DocTitle", parent=styles["Heading2"], textColor=TEXT,
                           fontSize=14, spaceBefore=10, spaceAfter=6))
styles.add(ParagraphStyle("Label", parent=styles["Normal"], textColor=MUTED, fontSize=9))
styles.add(ParagraphStyle("Value", parent=styles["Normal"], textColor=TEXT, fontSize=11))
styles.add(ParagraphStyle("Body", parent=styles["Normal"], textColor=TEXT, fontSize=10.5,
                           leading=15))
styles.add(ParagraphStyle("Right", parent=styles["Normal"], alignment=TA_RIGHT))
styles.add(ParagraphStyle("Center", parent=styles["Normal"], alignment=TA_CENTER))
styles.add(ParagraphStyle("AllergyWarning", parent=styles["Normal"], textColor=DANGER,
                           fontSize=11, leading=14, fontName="Helvetica-Bold"))


def _logo_flowable(logo_path, max_h=22 * mm):
    if logo_path and os.path.exists(logo_path):
        try:
            img = Image(logo_path)
            ratio = img.imageWidth / img.imageHeight
            img.drawHeight = max_h
            img.drawWidth = max_h * ratio
            return img
        except Exception:
            return None
    return None


def _letterhead(clinic, logo_path):
    rows = []
    name_block = [Paragraph(clinic.get("clinic_name") or "Feast9", styles["BrandTitle"])]
    meta_bits = [b for b in [
        clinic.get("clinic_address"), clinic.get("clinic_phone"), clinic.get("clinic_email")
    ] if b]
    if meta_bits:
        name_block.append(Paragraph(" &nbsp;|&nbsp; ".join(meta_bits), styles["ClinicMeta"]))
    logo = _logo_flowable(logo_path)
    if logo:
        t = Table([[logo, name_block]], colWidths=[26 * mm, None])
        t.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("ALIGN", (0, 0), (0, 0), "LEFT"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ]))
        rows.append(t)
    else:
        rows.extend(name_block)
    rows.append(Spacer(1, 4))
    rows.append(HRFlowable(width="100%", thickness=1.4, color=PRIMARY_LIGHT))
    rows.append(Spacer(1, 8))
    return rows


def _info_table(pairs, col_widths=(38 * mm, None)):
    data = [[Paragraph(f"<b>{label}</b>", styles["Label"]), Paragraph(str(value or "—"), styles["Value"])]
            for label, value in pairs]
    t = Table(data, colWidths=list(col_widths))
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 1),
    ]))
    return t


def _footer(text="Generated by Feast9 patient management system"):
    return [Spacer(1, 14), HRFlowable(width="100%", thickness=0.6, color=BORDER),
            Spacer(1, 4), Paragraph(text, styles["ClinicMeta"])]


def _build(buf, story, pagesize=A4, margins=18 * mm):
    doc = SimpleDocTemplate(buf, pagesize=pagesize,
                             leftMargin=margins, rightMargin=margins,
                             topMargin=margins, bottomMargin=margins)
    doc.build(story)
    return buf.getvalue()


def _money(v):
    try:
        return f"Rs. {float(v):,.2f}"
    except (TypeError, ValueError):
        return "Rs. 0.00"


# ---------------------------------------------------------------------------
# Prescription
# ---------------------------------------------------------------------------
def generate_prescription_pdf(patient: dict, case: dict, prescription: dict,
                                doctor_name: str, clinic: dict, logo_path: str = None) -> bytes:
    buf = io.BytesIO()
    story = []
    story += _letterhead(clinic, logo_path)
    story.append(Paragraph("PRESCRIPTION", styles["DocTitle"]))

    header = _info_table([
        ("Date", prescription.get("rx_date")),
        ("Patient Name", patient.get("name")),
        ("Age / Sex", f"{patient.get('age') or '—'} / {patient.get('sex') or '—'}"),
        ("Case", case.get("title")),
        ("Doctor", doctor_name or "—"),
    ])
    story.append(header)
    story.append(Spacer(1, 8))

    allergies = patient.get("allergies") or []
    allergies_other = patient.get("allergies_other") or ""
    if allergies or allergies_other:
        bits = list(allergies)
        if allergies_other:
            bits.append(allergies_other)
        warn_table = Table([[Paragraph(f"⚠ ALLERGY ALERT: {', '.join(bits)}",
                                        styles["AllergyWarning"])]], colWidths=[None])
        warn_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#FDECEA")),
            ("BOX", (0, 0), (-1, -1), 0.8, DANGER),
            ("TOPPADDING", (0, 0), (-1, -1), 7),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ]))
        story.append(warn_table)
        story.append(Spacer(1, 8))

    story.append(Spacer(1, 4))
    story.append(Paragraph("Rx", ParagraphStyle("RxLabel", parent=styles["Heading3"],
                                                  textColor=PRIMARY, fontSize=16)))
    story.append(Spacer(1, 4))
    for line in (prescription.get("rx_details") or "").split("\n"):
        story.append(Paragraph(line if line.strip() else "&nbsp;", styles["Body"]))
    story.append(Spacer(1, 40))
    sign_table = Table([[Paragraph("____________________", styles["Value"])]],
                        colWidths=[70 * mm])
    wrapper = Table([[Spacer(1, 1), sign_table]], colWidths=[None, 75 * mm])
    wrapper.setStyle(TableStyle([("ALIGN", (1, 0), (1, 0), "RIGHT")]))
    story.append(wrapper)
    story.append(Paragraph(f"<para alignment='right'>{doctor_name or 'Doctor'}</para>", styles["Value"]))
    story += _footer()
    return _build(buf, story)


