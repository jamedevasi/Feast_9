# Consent form
# ---------------------------------------------------------------------------
def generate_consent_pdf(patient: dict, case: dict, consent: dict, doctor_name: str,
                           clinic: dict, logo_path: str = None,
                           signature_image_path: str = None, blank: bool = False) -> bytes:
    buf = io.BytesIO()
    story = []
    story += _letterhead(clinic, logo_path)
    story.append(Paragraph("TREATMENT CONSENT FORM", styles["DocTitle"]))

    story.append(_info_table([
        ("Patient Name", patient.get("name")),
        ("Age / Sex", f"{patient.get('age') or '—'} / {patient.get('sex') or '—'}"),
        ("Case", case.get("title")),
        ("Doctor", doctor_name or "—"),
        ("Date", consent.get("signed_date") or "________________"),
    ]))
    story.append(Spacer(1, 12))

    for para in (consent.get("consent_text") or "").split("\n\n"):
        line_html = para.replace("\n", "<br/>")
        story.append(Paragraph(line_html, styles["Body"]))
        story.append(Spacer(1, 8))

    story.append(Spacer(1, 20))

    if blank:
        sig_cell = Paragraph("_____________________________", styles["Value"])
    elif signature_image_path and os.path.exists(signature_image_path):
        try:
            sig_img = Image(signature_image_path)
            ratio = sig_img.imageWidth / sig_img.imageHeight
            sig_img.drawHeight = 18 * mm
            sig_img.drawWidth = 18 * mm * ratio
            if sig_img.drawWidth > 70 * mm:
                sig_img.drawWidth = 70 * mm
                sig_img.drawHeight = 70 * mm / ratio
            sig_cell = sig_img
        except Exception:
            sig_cell = Paragraph("_____________________________", styles["Value"])
    else:
        sig_cell = Paragraph("(signed copy on file — see attachment)", styles["ClinicMeta"])

    sign_table = Table(
        [[sig_cell], [Paragraph("Patient / Guardian Signature", styles["Label"])]],
        colWidths=[80 * mm],
    )
    sign_table.setStyle(TableStyle([
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("TOPPADDING", (0, 1), (0, 1), 2),
        ("LINEBELOW", (0, 0), (0, 0), 0.6, BORDER),
    ]))
    story.append(sign_table)
    story.append(Spacer(1, 10))

    if consent.get("witness_name"):
        story.append(Paragraph(f"<b>Witness:</b> {consent['witness_name']}", styles["Body"]))
    if consent.get("notes"):
        story.append(Paragraph(f"<b>Notes:</b> {consent['notes']}", styles["Body"]))

    story += _footer()
    return _build(buf, story)


# ---------------------------------------------------------------------------
# DPDP Phase 2 — Right to Access: full data export PDF
# ---------------------------------------------------------------------------
def generate_data_access_pdf(patient: dict, cases: list, payments_by_case: dict,
                               prescriptions_by_case: dict, consents_by_case: dict,
                               appointments: list, clinic: dict,
                               logo_path: str = None) -> bytes:
    """Generates a comprehensive export of all data held on a patient —
    the response to a Right to Access request under Section 11, DPDP Act 2023."""
    buf = io.BytesIO()
    story = []
    story += _letterhead(clinic, logo_path)
    story.append(Paragraph("PATIENT DATA EXPORT", styles["DocTitle"]))
    story.append(Paragraph(
        "This document contains all personal and clinical data held by this practice "
        "about the patient named below. It is issued in response to a Right to Access "
        "request under Section 11, Digital Personal Data Protection Act 2023.",
        styles["ClinicMeta"]))
    story.append(Spacer(1, 10))

    # Personal details
    story.append(Paragraph("Personal Details", ParagraphStyle(
        "Sub", parent=styles["Heading4"], textColor=MUTED)))
    story.append(_info_table([
        ("Name",              patient.get("name")),
        ("Age / Sex",         f"{patient.get('age') or '—'} / {patient.get('sex') or '—'}"),
        ("Mobile",            patient.get("mobile")),
        ("Email",             patient.get("email") or "—"),
        ("Address",           patient.get("address") or "—"),
        ("Last Visited",      patient.get("last_visited_date") or "—"),
        ("Emergency Contact", f"{patient.get('emergency_contact_name') or '—'}"
                              f" ({patient.get('emergency_contact_relation') or '—'})"
                              f" {patient.get('emergency_contact_number') or ''}"),
    ]))
    story.append(Spacer(1, 8))

    # Medical history
    conds = patient.get("medical_conditions") or []
    allergies = patient.get("allergies") or []
    story.append(Paragraph("Medical History on File", ParagraphStyle(
        "Sub2", parent=styles["Heading4"], textColor=MUTED)))
    story.append(_info_table([
        ("Conditions",      ", ".join(conds) or "None recorded"),
        ("Other notes",     patient.get("medical_conditions_other") or "—"),
        ("Allergies",       ", ".join(allergies) or "None recorded"),
        ("Other allergies", patient.get("allergies_other") or "—"),
        ("Pregnant",        "Yes" if patient.get("is_pregnant") else "No"),
        ("Nursing",         "Yes" if patient.get("is_nursing") else "No"),
    ]))
    story.append(Spacer(1, 8))

    # Consent status
    story.append(Paragraph("Consent Records", ParagraphStyle(
        "Sub3", parent=styles["Heading4"], textColor=MUTED)))
    story.append(_info_table([
        ("Data Processing Notice", "Acknowledged" if patient.get("dpdp_notice_accepted")
                                   else "Not yet acknowledged"),
        ("Notice Acknowledged At", patient.get("dpdp_notice_accepted_at") or "—"),
        ("Communications Consent", "Yes" if patient.get("comms_consent") else "No (opted out)"),
    ]))
    story.append(Spacer(1, 10))

    # Treatment cases
    if cases:
        story.append(Paragraph("Treatment Cases", ParagraphStyle(
            "Sub4", parent=styles["Heading4"], textColor=MUTED)))
        for c in cases:
            story.append(Paragraph(f"<b>{c['title']}</b> — {c['status']}",
                                    styles["Body"]))
            procs = ", ".join(c.get("procedures") or []) or "—"
            story.append(_info_table([
                ("Doctor",     c.get("doctor_name") or "—"),
                ("Procedures", procs),
                ("Total Cost", _money(c.get("total_cost", 0))),
                ("Opened",     c.get("created_at") or "—"),
                ("Closed",     c.get("closed_at") or "—"),
            ], col_widths=(30 * mm, None)))
            # Payments for this case
            pmts = payments_by_case.get(c["id"], [])
            if pmts:
                pmt_data = [["Date", "Amount", "Method"]]
                for p in pmts:
                    pmt_data.append([p["payment_date"], _money(p["amount"]),
                                      p.get("method") or "—"])
                pt = Table(pmt_data, colWidths=[24*mm, 28*mm, 28*mm])
                pt.setStyle(TableStyle([
                    ("BACKGROUND", (0,0), (-1,0), PRIMARY),
                    ("TEXTCOLOR", (0,0), (-1,0), colors.white),
                    ("FONTSIZE", (0,0), (-1,-1), 8),
                    ("GRID", (0,0), (-1,-1), 0.4, BORDER),
                    ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, ACCENT]),
                    ("TOPPADDING", (0,0), (-1,-1), 3),
                    ("BOTTOMPADDING", (0,0), (-1,-1), 3),
                ]))
                story.append(pt)
            # Prescriptions
            rxs = prescriptions_by_case.get(c["id"], [])
            for rx in rxs:
                rx_html = (rx['rx_details'] or "").replace("\n", "<br/>")
                story.append(Paragraph(f"<b>Rx {rx['rx_date']}:</b> {rx_html}",
                                        styles["Body"]))
            story.append(Spacer(1, 8))

    # Appointments
    if appointments:
        story.append(Paragraph("Appointments", ParagraphStyle(
            "Sub5", parent=styles["Heading4"], textColor=MUTED)))
        data = [["Date", "Time", "Doctor", "Reason", "Status"]]
        for a in appointments:
            data.append([a["appt_date"], a["start_time"],
                          a.get("doctor_name") or "—",
                          a.get("title") or "—", a.get("status") or "—"])
        at = Table(data, colWidths=[22*mm, 16*mm, 32*mm, 40*mm, 22*mm])
        at.setStyle(TableStyle([
            ("BACKGROUND", (0,0), (-1,0), PRIMARY),
            ("TEXTCOLOR", (0,0), (-1,0), colors.white),
            ("FONTSIZE", (0,0), (-1,-1), 8),
            ("GRID", (0,0), (-1,-1), 0.4, BORDER),
            ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, ACCENT]),
            ("TOPPADDING", (0,0), (-1,-1), 3),
            ("BOTTOMPADDING", (0,0), (-1,-1), 3),
        ]))
        story.append(at)
        story.append(Spacer(1, 8))

    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.6, color=BORDER))
    story.append(Spacer(1, 4))
    story.append(Paragraph(
        f"Export generated on {__import__('datetime').date.today().isoformat()} in response to "
        "a Right to Access request (Section 11, DPDP Act 2023). "
        "Retention period: clinical records 7 years from last visit; "
        "communications data as long as necessary.",
        styles["ClinicMeta"]))
    story += _footer()
    return _build(buf, story)
